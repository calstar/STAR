/**
 * Boards-page DHCP status, parsed from what star-dhcp actually serves and logs.
 * Fixtures are verbatim from star-rfs on 2026-09-26.
 */
import { describe, it, expect } from 'vitest';
import { parseHosts, parseAcks, dhcpStatusFor, parseSyncError } from '../dhcp-status.js';

const HOSTS = `# GENERATED by generate_dhcp_config.py — do not edit by hand.
# Reservations reload on SIGHUP (systemctl reload star-dhcp). One per line:
#   <mac>,<ip>,<hostname>,infinite

4a:27:e2:3a:d5:49,192.168.2.21,pt-board,infinite
4a:27:e2:3a:ad:71,192.168.2.31,rtd-board,infinite
`;

const JOURNAL = `1790468568.100000 star-rfs dnsmasq-dhcp[3529886]: 4187409647 DHCPACK(enp4s0) 192.168.2.227 30:68:93:ad:2e:5d TL-SG116E
1790468597.500000 star-rfs dnsmasq-dhcp[3529886]: 797 DHCPACK(enp4s0) 192.168.2.31 4a:27:e2:3a:ad:71 rtd-board
1790468400.000000 star-rfs dnsmasq-dhcp[3529886]: 12 DHCPACK(enp4s0) 192.168.2.31 4A:27:E2:3A:AD:71 rtd-board
1790468597.600000 star-rfs dnsmasq-dhcp[3529886]: 797 DHCPREQUEST(enp4s0) 192.168.2.31 4a:27:e2:3a:ad:71
`;

describe('parseHosts', () => {
  it('keys reservations by IP and skips comments and blanks', () => {
    const h = parseHosts(HOSTS);
    expect(h.size).toBe(2);
    expect(h.get('192.168.2.31')).toEqual({ mac: '4a:27:e2:3a:ad:71', hostname: 'rtd-board' });
  });
});

describe('parseAcks', () => {
  it('keeps the latest DHCPACK per MAC, case-insensitive, ignoring other verbs', () => {
    const a = parseAcks(JOURNAL);
    expect(a.get('4a:27:e2:3a:ad:71')).toEqual({ ip: '192.168.2.31', atMs: 1790468597500 });
    expect(a.get('30:68:93:ad:2e:5d')?.ip).toBe('192.168.2.227');
    expect(a.size).toBe(2);
  });
});

describe('dhcpStatusFor', () => {
  const hosts = parseHosts(HOSTS);
  const acks = parseAcks(JOURNAL);

  it('a reserved board that handshook reports the ACK', () => {
    expect(dhcpStatusFor('192.168.2.31', hosts, acks)).toEqual({
      reserved: true, mac: '4a:27:e2:3a:ad:71', hostname: 'rtd-board',
      lastAckMs: 1790468597500, lastAckIp: '192.168.2.31',
    });
  });

  it('a reserved board with no ACK is not reported as served', () => {
    // pt-board is reserved but still on static-IP firmware: no handshake.
    const s = dhcpStatusFor('192.168.2.21', hosts, acks);
    expect(s.reserved).toBe(true);
    expect(s.lastAckMs).toBeUndefined();
  });

  it('a board with no reservation is not reserved, even if a pool lease exists', () => {
    expect(dhcpStatusFor('192.168.2.61', hosts, acks)).toEqual({ reserved: false });
  });
});

describe('parseSyncError', () => {
  it('reports the refusal while it is the latest run', () => {
    const j = [
      'wrote /etc/star-dhcp/star-dhcp.hosts: 9 reservation(s) from /x/config.toml',
      "error: board 'rtd_board' has board_id 32 but ip 192.168.2.31: the board takes its ID from its address, so these must agree",
    ].join('\n');
    expect(parseSyncError(j)).toMatch(/^board 'rtd_board' has board_id 32/);
  });

  it('clears once a later run succeeds', () => {
    const j = [
      "error: board 'rtd_board' has board_id 32 but ip 192.168.2.31",
      'wrote /etc/star-dhcp/star-dhcp.hosts: 9 reservation(s) from /x/config.toml',
    ].join('\n');
    expect(parseSyncError(j)).toBeUndefined();
    expect(parseSyncError('')).toBeUndefined();
  });
});
