"""A saved design becomes the same request bodies on the server as in the browser.

The cases in fixtures/design_requests/ are written by hand from the rules (typed
mass beats material, hidden parts still count, ISA sends no pad numbers, ...), not
generated by either implementation. This file holds backend/design_requests.py to
them; frontend/src/lib/designRequests.test.ts holds the browser's copy to the same
files. A change to one conversion the other does not make fails one of the two.
"""

from __future__ import annotations

import json
import math
import os
import re
import sys
from pathlib import Path

import pytest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from backend import design_requests as dr  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
CASES = sorted((ROOT / "tests" / "fixtures" / "design_requests").glob("*.json"))


def _close(a, b, path="$"):
    """Deep equality, floats to 1e-12 relative (the airframe band is computed, not copied)."""
    if isinstance(a, float) or isinstance(b, float):
        assert isinstance(a, (int, float)) and isinstance(b, (int, float)), f"{path}: {a!r} vs {b!r}"
        assert math.isclose(a, b, rel_tol=1e-12, abs_tol=1e-15), f"{path}: {a!r} != {b!r}"
    elif isinstance(a, dict) and isinstance(b, dict):
        assert set(a) == set(b), f"{path}: keys {sorted(set(a) ^ set(b))} differ"
        for k in a:
            _close(a[k], b[k], f"{path}.{k}")
    elif isinstance(a, list) and isinstance(b, list):
        assert len(a) == len(b), f"{path}: {len(a)} items vs {len(b)}"
        for i, (x, y) in enumerate(zip(a, b)):
            _close(x, y, f"{path}[{i}]")
    else:
        assert a == b, f"{path}: {a!r} != {b!r}"


@pytest.mark.parametrize("case", CASES, ids=[c.stem for c in CASES])
def test_each_case(case):
    c = json.loads(case.read_text())
    got = dr.all_requests(c["config"], c["manifestParts"])
    exp = c["expected"]
    _close(got["flightDynamics"], exp["flightDynamics"])
    _close(got["ork"], {**exp["flightDynamics"], "devices": exp["ork_devices"]})
    _close(got["recovery"], exp["recovery"])
    stability = {k: v for k, v in exp["flightDynamics"].items() if k not in ("inclination", "heading", "site", "wind", "railLength")}
    _close(got["stability"], stability)


def test_there_are_cases():
    assert len(CASES) >= 2


def test_materials_match_the_frontend_catalog():
    """MATERIAL_DENSITY is a copy of materials.ts; parse that file so the two cannot drift."""
    src = (ROOT / "frontend" / "src" / "lib" / "materials.ts").read_text()
    ts = {k: float(d) for k, d in re.findall(r"key:\s*'([^']+)'.*?density:\s*([0-9.]+)", src)}
    assert ts and ts == dr.MATERIAL_DENSITY


def test_cad_defaults_match_the_frontend():
    src = (ROOT / "frontend" / "src" / "types" / "config.ts").read_text()
    assert re.search(r"railLength:\s*1\.0\b", src) and dr.CAD_DEFAULTS["railLength"] == 1.0
    m = re.search(r"inclination:\s*([0-9.]+),\s*heading:\s*([0-9.]+)", src)
    assert m and (float(m.group(1)), float(m.group(2))) == (
        dr.FLIGHT_DEFAULTS["inclination"],
        dr.FLIGHT_DEFAULTS["heading"],
    )


def test_a_missing_recovery_field_is_named_not_guessed():
    c = json.loads((ROOT / "tests" / "fixtures" / "design_requests" / "overrides_and_isa.json").read_text())
    del c["config"]["recovery"]["sweep"]
    with pytest.raises(dr.DesignError, match="sweep"):
        dr.all_requests(c["config"], c["manifestParts"])


def test_no_model_is_an_error():
    with pytest.raises(dr.DesignError, match="modelId"):
        dr.model_id({"cad": {}})


# ── the endpoint ─────────────────────────────────────────────────────────────

pytest.importorskip("fastapi")


def test_endpoint_reads_the_models_manifest(tmp_path, monkeypatch):
    from fastapi.testclient import TestClient

    from backend import main

    c = json.loads((ROOT / "tests" / "fixtures" / "design_requests" / "overrides_and_isa.json").read_text())
    model = tmp_path / "m-test"
    model.mkdir()
    (model / "manifest.json").write_text(json.dumps({"schemaVersion": 2, "parts": c["manifestParts"]}))
    monkeypatch.setattr(main, "CACHE_ROOT", tmp_path)
    client = TestClient(main.app)

    r = client.post("/api/design/requests", json={"config": c["config"]})
    assert r.status_code == 200, r.text
    body = r.json()
    assert body["modelId"] == "m-test"
    assert body["airframeBound"] == "broadside"
    _close(body["flightDynamics"], c["expected"]["flightDynamics"])

    bad = json.loads(json.dumps(c["config"]))
    del bad["recovery"]["devices"]
    r = client.post("/api/design/requests", json={"config": bad})
    assert r.status_code == 422 and "devices" in r.json()["detail"]

    r = client.post("/api/design/requests", json={"config": {**c["config"], "cad": {"modelId": "nope"}}})
    assert r.status_code == 404
